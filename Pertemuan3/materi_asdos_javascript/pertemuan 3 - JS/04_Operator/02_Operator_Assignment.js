// Deklarasi variabel
let x = 10;
console.log("Nilai awal x:", x);

// Operator assignment dasar (=)
x = 20;
console.log("Setelah assignment =", x);

// Operator penjumlahan assignment (+=)
x += 5; // sama dengan x = x + 5
console.log("Setelah += 5:", x);

// Operator pengurangan assignment (-=)
x -= 3; // sama dengan x = x - 3
console.log("Setelah -= 3:", x);

// Operator perkalian assignment (*=)
x *= 2; // sama dengan x = x * 2
console.log("Setelah *= 2:", x);

// Operator pembagian assignment (/=)
x /= 4; // sama dengan x = x / 4
console.log("Setelah /= 4:", x);

// Operator modulus assignment (%=)
x %= 3; // sama dengan x = x % 3
console.log("Setelah %= 3:", x);

// Operator eksponensial assignment (**=)
x **= 2; // sama dengan x = x ** 2
console.log("Setelah **= 2:", x);