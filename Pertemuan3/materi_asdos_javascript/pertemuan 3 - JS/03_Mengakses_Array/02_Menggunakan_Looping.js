let angka = [1, 2, 3, 4, 5];

// Menggunakan perulangan for
for (let i = 0; i < angka.length; i++) {
  console.log(angka[i]); 
  // Output: 1, 2, 3, 4, 5 (dicetak satu per satu)
}
// Membuat array buah
let buah = ['Apel', 'Pisang', 'Jeruk'];
let i = 0;

// Menggunakan perulangan while
while (i < buah.length) {
  console.log(buah[i]); 
  // Akan mencetak: Apel, Pisang, Jeruk
  i++;
}

